# ============================================================
# FPGA 仿真源文件列表
#
# 作用：
#   这个文件用来告诉仿真脚本：
#   1. 哪些 HDL 文件需要参与仿真
#   2. 按照什么顺序进行编译
#
# 使用规则：
#
#   .v
#       按 Verilog 语言编译
#
#   .sv
#       按 SystemVerilog 语言编译
#
#   .vh / .svh
#       一般不需要单独写入此文件
#       它们通过 `include 被其他文件引用
#
#   +incdir+
#       指定头文件搜索目录
#
# 注意：
#   编译顺序非常重要。
#
#   例如：
#
#       common_pkg.sv
#       ↓
#       controller.sv
#
#   如果 controller.sv 中使用：
#
#       import common_pkg::*;
#
#   那么 common_pkg.sv 必须写在 controller.sv 前面。
# ============================================================


